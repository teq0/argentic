#!/usr/bin/env python3
"""Translates docs/design/sterling2-formulae.cpp into Metal Shading Language.

Usage (from the repository root):
    PYTHONPATH= python3 app/Tools/translate_formulae.py

Writes app/Sources/ArgenticCore/GeneratedFormulas.swift. Do not edit that file by hand.

The source is mechanical enough to translate with a handful of rewrites:
  * `v->z`, `v->c`, `v->Iteration` ... become locals of the generated function
  * the orbit stores inside the loop become `ORBIT(z)` (a macro that feeds the render stage)
  * the stores after the loop are dropped: the original render stage never reads them
  * `__real__ x` / `__imag__ x` become `x.x` / `x.y`
  * helper calls get explicit arguments (the C++ used implicit globals)
  * float literals get an `f` suffix because MSL has no `double`
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/design/sterling2-formulae.cpp"
OUTPUT = ROOT / "app/Sources/ArgenticCore/GeneratedFormulas.swift"

LOCALS = ["z1", "z2", "z3", "z4", "z5", "z6", "z7", "z8", "zsin", "zcos", "zd", "c2"]


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def split_functions(text: str):
    """Yields (index, body) for each `void Formula_NN(CDATA *v) { ... }`."""
    for m in re.finditer(r"void\s+Formula_(\d+)\s*\(\s*CDATA\s*\*\s*v\s*\)\s*\{", text):
        depth = 1
        i = m.end()
        while depth:
            ch = text[i]
            depth += (ch == "{") - (ch == "}")
            i += 1
        yield int(m.group(1)), text[m.end(): i - 1]


STORE = re.compile(
    r"v->pXTemp\[v->Iteration\]\s*=\s*__real__\s+([\w>-]+)\s*;\s*"
    r"v->pYTemp\[v->Iteration\]\s*=\s*__imag__\s+\1\s*;"
)


def rewrite_stores(body: str) -> str:
    """In-loop stores (brace depth >= 1 inside the body) feed the render stage; later ones are dropped."""
    out = []
    pos = 0
    for m in STORE.finditer(body):
        out.append(body[pos:m.start()])
        depth = body[:m.start()].count("{") - body[:m.start()].count("}")
        out.append(f"ORBIT({m.group(1)});" if depth >= 1 else "")
        pos = m.end()
    out.append(body[pos:])
    return "".join(out)


def translate(index: int, body: str) -> str:
    body = rewrite_stores(body)
    body = body.replace("v->Iteration", "it").replace("v->Maxit", "maxit")
    body = body.replace("v->dStrands", "dStrands").replace("v->jul", "jul")
    body = body.replace("v->z", "vz").replace("v->c", "vc")
    body = re.sub(r"__real__\s+([A-Za-z_]\w*)", r"\1.x", body)
    body = re.sub(r"__imag__\s+([A-Za-z_]\w*)", r"\1.y", body)
    body = body.replace("sine_cosine()", "sine_cosine(z, zsin, zcos)")
    for name in ("clog_z", "cexp_z", "ctan_z", "csin_z"):
        body = body.replace(f"{name}()", f"{name}(z)")
    body = body.replace("sum_sqrs_zd()", "sum_sqrs(zd)")
    # MSL has no double: make every floating literal a float.
    body = re.sub(r"(?<![\w.])(\d+\.\d*(?:[eE][-+]?\d+)?|\d+[eE][-+]?\d+)(?![\w.])", r"\1f", body)
    if re.search(r"v->|__real__|__imag__|pXTemp|pYTemp", body):
        raise SystemExit(f"Formula_{index:02d}: unhandled construct remains:\n{body}")

    decls = ", ".join(LOCALS)
    lines = [
        f"inline int Formula_{index:02d}(thread OrbitAcc &S, cplx vz, cplx vc, int maxit, int jul, float dStrands) {{",
        "    int it = 0;",
        "    cplx z = vz;",
        "    cplx c = vc;",
        f"    cplx {decls};",
        "    float temp = 1.0f;",
    ]
    lines += [l.rstrip() for l in body.strip("\n").split("\n")]
    lines += ["    return it;", "}", ""]
    return "\n".join(lines)


def main() -> None:
    text = strip_comments(SOURCE.read_text(encoding="latin-1"))
    functions = [translate(i, b) for i, b in split_functions(text)]
    indices = [int(m.group(1)) for m in re.finditer(r"inline int Formula_(\d+)\(", "\n".join(functions))]

    cases = "\n".join(f"    case {i}: return Formula_{i:02d}(S, vz, vc, maxit, jul, dStrands);" for i in indices)
    dispatch = (
        "inline int runFormula(int formula, thread OrbitAcc &S, cplx vz, cplx vc, int maxit, int jul, float dStrands) {\n"
        "    switch (formula) {\n"
        f"{cases}\n"
        "    default: return 0;\n"
        "    }\n"
        "}\n"
    )
    swift = (
        "// Generated by app/Tools/translate_formulae.py from docs/design/sterling2-formulae.cpp. Do not edit.\n\n"
        "enum GeneratedFormulas {\n"
        "    static let implemented: [Int] = [" + ", ".join(map(str, indices)) + "]\n\n"
        '    static let source = #"""\n'
        + "\n".join(functions) + "\n" + dispatch +
        '"""#\n'
        "}\n"
    )
    OUTPUT.write_text(swift)
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(indices)} formulas")


if __name__ == "__main__":
    sys.exit(main())

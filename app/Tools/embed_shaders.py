#!/usr/bin/env python3
"""Embeds app/Shaders/render_shared.h into app/Sources/ArgenticCore/SharedRenderSource.swift.

The header is compiled by Metal (real = float) via that Swift string, and by the C++ oracle (real = double)
via #include, so both run the same text.

Usage (from the repository root):
    PYTHONPATH= python3 app/Tools/embed_shaders.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "app/Shaders/render_shared.h"
OUTPUT = ROOT / "app/Sources/ArgenticCore/SharedRenderSource.swift"

text = HEADER.read_text()
assert '"""' not in text, "header must not contain a Swift multi-line string delimiter"
OUTPUT.write_text(
    "// Generated by app/Tools/embed_shaders.py from app/Shaders/render_shared.h. Do not edit.\n\n"
    "enum SharedRenderSource {\n"
    '    static let source = #"""\n'
    + text
    + ('' if text.endswith("\n") else "\n")
    + '"""#\n'
    "}\n"
)
print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(text)} chars)")

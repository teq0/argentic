#!/usr/bin/env python3
"""Compile the same formula/render/colour algorithms as Metal as double-precision C++.

Run after editing MetalShaderSource.swift or FormulaConstants.swift, translating formulas,
or changing render_shared.h.
The generated header is checked in so consumers need only a C++ compiler, not Python.
"""
from pathlib import Path
import re
import textwrap

ROOT = Path(__file__).resolve().parents[2]
CORE = ROOT / "app/Sources/ArgenticCore"
text = (CORE / "MetalShaderSource.swift").read_text().split('static let source = """', 1)[1].rsplit('"""', 1)[0]
text = textwrap.dedent(text).strip()
# Resolve shared Swift formula IDs before compiling the same shader algorithms as C++.
constants = re.findall(r"public let (\w+)\s*=\s*(\d+)\b", (CORE / "FormulaConstants.swift").read_text())
if not constants:
    raise SystemExit("No formula IDs found in FormulaConstants.swift")
for name, value in constants:
    text = text.replace("\\(" + name + ")", value)
if re.search(r"\\\(\w+FormulaID\)", text):
    raise SystemExit("An unresolved formula ID remains in the CPU shader source")
formulas = (CORE / "GeneratedFormulas.swift").read_text().split('static let source = #"""', 1)[1].rsplit('"""#', 1)[0]
text = text.replace(r"\(GeneratedFormulas.source)", formulas)
text = text.replace(r"\(SharedRenderSource.source)", (ROOT / "app/Shaders/render_shared.h").read_text())
text = text.replace("#include <metal_stdlib>", "").replace("using namespace metal;", "")
text = re.sub(r"\[\[.*?\]\]", "", text)
for name in ("kFormula", "kRender", "kTransform"):
    text = re.sub(rf"constant int {name}\s*;", f"static thread_local int {name};", text)
text = re.sub(r"constant bool kUseOrbit = .*?;", "static thread_local bool kUseOrbit;", text)
text = re.sub(r"\bconstant\b", "const", text)
text = re.sub(r"\b(thread|device|kernel)\b", "", text)
text = text.replace("precise::", "std::")
text = re.sub(r"\bfloat\b", "double", text)
text = re.sub(r"(?<![\w.])(\d+\.\d*(?:[eE][+-]?\d+)?|\d+[eE][+-]?\d+)f\b", r"\1", text)
# Single-thread scratch storage is reused for each pixel, rather than GPU-interleaved per band.
text = text.replace("orb.stride = p.orbitStride;", "orb.stride = 1;")
text = text.replace("orb.tid = uint(gid.y) * uint(p.fieldWidth) + gid.x;", "orb.tid = 0;")
# CPU doubles do not need the GPU's reduced exponential clamp.
text = text.replace("fabs(v) > 30.0 ? (v > 0.0 ? 30.0 : -30.0)", "fabs(v) > 50.0 ? (v > 0.0 ? 50.0 : -50.0)")
text = text.replace("std::exp(clampIm(z.x))", "std::exp(clamp50(z.x))")
# Match the independent oracle's in-place clamping, which double precision can preserve.
for helper in ("csin_z", "cexp_z", "clog_z"):
    clamp = "guardTiny(clamp50(z.{axis}))" if helper == "csin_z" else "clamp50(z.{axis})"
    body = " ".join(f"z.{axis} = {clamp.format(axis=axis)};" for axis in ("x", "y"))
    text = text.replace(f"inline cplx {helper}(cplx z) {{", f"inline cplx {helper}(cplx &z) {{ {body}")
text = text.replace("9.223372e18", "9223372036854775808.0")
# Poll cancellation inside long formula and Lyapunov orbits, as well as between pixels.
text = text.replace("void set(int i, real x, real y) {", "void set(int i, real x, real y) { pollCancellation();")
text = text.replace("real X(int i) {", "real X(int i) { pollCancellation();")
text = text.replace("real Y(int i) {", "real Y(int i) { pollCancellation();")
text = text.replace("void add(cplx p, int index) {", "void add(cplx p, int index) { pollCancellation();")
# The original intentionally rounds these two blend-26 products to single precision.
text = text.replace("d1 = d0 * 0.5 * a;", "d1 = float(d0) * 0.5f * float(a);")
text = text.replace("d2 = d0 * 0.5 * b;", "d2 = float(d0) * 0.5f * float(b);")
output = ROOT / "app/Sources/ArgenticCPU/Algorithms.hpp"
output.write_text("// Generated by app/Tools/generate_cpu_renderer.py. Do not edit.\n" + text + "\n")
print(f"wrote {output.relative_to(ROOT)}")
